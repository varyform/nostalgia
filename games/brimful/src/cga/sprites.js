export function canvas(w, h) {
  const c = document.createElement('canvas');
  c.width = w; c.height = h;
  return c;
}
function paint(rows, pal, shirt, flip) {
  const h = rows.length, w = Math.max(...rows.map(r => r.length)), c = canvas(w, h), x = c.getContext('2d');
  for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) {
    let ch = rows[j][flip ? w - 1 - i : i];
    if (ch === undefined || ch === '.') continue;
    if (ch === 'S') ch = shirt;
    x.fillStyle = pal[+ch];
    x.fillRect(i, j, 1, 1);
  }
  return c;
}
// all sprites in one palette: get(name, flip, shirt)
export function buildSprites(pal) {
  const cache = new Map();
  return (name, flip = false, shirt = '1', rows = SPRITES[name]) => {
    const key = name + (flip ? '<' : '>') + shirt;
    let c = cache.get(key);
    if (!c) { c = paint(rows, pal, shirt, flip); cache.set(key, c); }
    return c;
  };
}
