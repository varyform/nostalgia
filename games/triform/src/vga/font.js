const GLYPHS = {};
for (const k in SRC) GLYPHS[k] = SRC[k].split(' ').map(r => parseInt(r, 2));

export const FONT_H = 7;
export const textWidth = (s, sc = 1) => Math.max(0, String(s).length * 6 - 1) * sc;

// draw s with its top-left at x,y; `fill` is a colour or a function of the glyph row (gradients)
export function drawText(g, s, x, y, fill, sc = 1, shadow = null) {
  s = String(s).toUpperCase();
  x = Math.round(x); y = Math.round(y);
  if (shadow) drawText(g, s, x + sc, y + sc, shadow, sc);
  let cx = x;
  for (const ch of s) {
    const gl = GLYPHS[ch];
    if (gl)
      for (let r = 0; r < 7; r++) {
        const bits = gl[r];
        if (!bits) continue;
        g.fillStyle = typeof fill === 'function' ? fill(r) : fill;
        for (let k = 0; k < 5; k++) if (bits & (16 >> k)) g.fillRect(cx + k * sc, y + r * sc, sc, sc);
      }
    cx += 6 * sc;
  }
  return cx - x;
}

// greedy word wrap to a pixel width
export function wrap(s, width, sc = 1) {
  const out = [];
  let line = '';
  for (const w of String(s).split(' ')) {
    const t = line ? line + ' ' + w : w;
    if (textWidth(t, sc) > width && line) { out.push(line); line = w; } else line = t;
  }
  if (line) out.push(line);
  return out;
}
